import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const output = fileURLToPath(
  new URL('../crates/sable-model/src/emoji_properties.rs', import.meta.url)
);

function ranges(property) {
  const pattern = new RegExp(`^\\p{${property}}$`, 'u');
  const found = [];
  let start = -1;
  for (let code = 0; code <= 0x110000; code += 1) {
    const surrogate = code >= 0xd800 && code <= 0xdfff;
    const matches = code < 0x110000 && !surrogate && pattern.test(String.fromCodePoint(code));
    if (matches && start < 0) start = code;
    if (!matches && start >= 0) {
      found.push([start, code - 1]);
      start = -1;
    }
  }
  return found;
}

function table(name, property) {
  const hex = (code) => `0x${code.toString(16).toUpperCase()}`;
  const rows = ranges(property).map(([from, to]) => `    (${hex(from)}, ${hex(to)}),`);
  return `pub(crate) const ${name}: &[(u32, u32)] = &[\n${rows.join('\n')}\n];\n`;
}

await writeFile(
  output,
  [
    `//! Generated by \`scripts/generate-emoji-properties.mjs\` from Unicode ${process.versions.unicode}.`,
    '',
    table('EXTENDED_PICTOGRAPHIC', 'Extended_Pictographic'),
    table('EMOJI_COMPONENT', 'Emoji_Component'),
  ].join('\n')
);
