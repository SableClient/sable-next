import { describe, expect, it, vi } from 'vitest';
import en from '../../locales/en.json';
import { ACCOUNT_PREFERENCES } from '#lib/settings/definitions.js';
import { parseAccountConfig } from './account-config';
import { RuntimeSchema } from './runtime-config';

type Schema = Record<string, unknown>;

const PLATFORM_DEFAULTS = new Set(['reducedMotion', 'updateChannel', 'useCustomTitleBar']);

function translate(key: string): string {
  const value = key.split('.').reduce<unknown>((node, part) => {
    return typeof node === 'object' && node !== null
      ? (node as Record<string, unknown>)[part]
      : undefined;
  }, en);
  return typeof value === 'string' ? value : key;
}

async function loadSettings() {
  vi.resetModules();
  // Telemetry and desktop settings are only registered where they apply.
  vi.stubEnv('VITE_SENTRY_DSN', 'https://key@example.org/1');
  vi.stubGlobal('sableElectron', {});
  const { preferenceSpecs } = await import('#lib/settings/definitions.js');
  const { settingsCategories } = await import('#lib/settings/registry.js');
  vi.unstubAllEnvs();
  vi.unstubAllGlobals();
  const placement = new Map<string, { category: string; label: string }>();
  for (const category of settingsCategories)
    for (const item of category.items)
      if (!placement.has(item.key))
        placement.set(item.key, {
          category: translate(category.name),
          label: translate(item.name),
        });
  return { specs: preferenceSpecs(), placement };
}

type Settings = Awaited<ReturnType<typeof loadSettings>>;
type Spec = Settings['specs'][number];

const code = (value: unknown) => `\`${typeof value === 'string' ? value : JSON.stringify(value)}\``;

function settingSchema(spec: Spec, label: string | undefined): Schema {
  const schema: Schema = label ? { title: label } : {};
  switch (spec.type) {
    case 'boolean':
      schema.type = 'boolean';
      break;
    case 'text':
      schema.type = 'string';
      break;
    case 'number':
      Object.assign(schema, { type: 'number', minimum: spec.min, maximum: spec.max });
      break;
    case 'list':
      Object.assign(schema, { type: 'array', uniqueItems: true, items: { enum: spec.values } });
      break;
    case 'enum':
      if (spec.key === 'timeZone') schema.type = 'string';
      else schema.enum = spec.values;
  }
  if (!PLATFORM_DEFAULTS.has(spec.key)) schema.default = spec.default;
  return schema;
}

function describeValues(spec: Spec): string {
  const defaultText = PLATFORM_DEFAULTS.has(spec.key)
    ? 'The default depends on the platform.'
    : `Default ${spec.default === '' ? 'empty' : code(spec.default)}.`;
  switch (spec.type) {
    case 'boolean':
      return `\`true\` or \`false\`. ${defaultText}`;
    case 'text':
      return `Text. ${defaultText}`;
    case 'number':
      return `Number from ${spec.min} to ${spec.max}. ${defaultText}`;
    case 'list':
      return `List of ${spec.values.map(code).join(', ')}. ${defaultText}`;
    case 'enum':
      if (spec.key === 'timeZone') return `An IANA time zone name or \`auto\`. ${defaultText}`;
      return `One of ${spec.values.map(code).join(', ')}. ${defaultText}`;
  }
}

function settingsMarkdown({ specs, placement }: Settings): string {
  const groups = new Map<string, Spec[]>();
  for (const spec of specs) {
    const category = placement.get(spec.key)?.category ?? 'Other';
    groups.set(category, [...(groups.get(category) ?? []), spec]);
  }
  const other = groups.get('Other');
  groups.delete('Other');
  if (other) groups.set('Other', other);

  const lines = [
    '<!-- Generated by src/lib/config/config-reference.test.ts. Regenerate with',
    '     pnpm vitest run --project node src/lib/config/config-reference.test.ts -u -->',
    '',
    '# Settings reference',
    '',
    'These names and values are accepted by `settingsDefaults` and `settingsLocked` in',
    '[`config.json`](web.md#configuration). Invalid values are ignored, and numbers outside',
    'their range are clamped.',
    '',
    '[`/.well-known/sable`](web.md#homeserver-configuration) accepts the same settings',
    'except those marked deployment only.',
  ];
  const accountKeys = new Set<string>(ACCOUNT_PREFERENCES);
  for (const [category, entries] of groups) {
    lines.push('', `## ${category}`, '');
    for (const spec of entries) {
      const label = placement.get(spec.key)?.label;
      const scope = accountKeys.has(spec.key) ? '' : ' Deployment only.';
      lines.push(`- \`${spec.key}\`${label ? ` (${label})` : ''}: ${describeValues(spec)}${scope}`);
    }
  }
  return `${lines.join('\n')}\n`;
}

const nullable = (schema: Schema): Schema => ({ ...schema, type: [schema.type, 'null'] });
const httpUrl = { type: 'string', pattern: '^https?://' };
const assetUrl = { type: 'string', pattern: '^(https?://|/)' };
const strict = (properties: Record<string, Schema>, required?: string[]): Schema => ({
  type: 'object',
  additionalProperties: false,
  properties,
  ...(required ? { required } : {}),
});

function policySections(settings: Schema, accountOnly: boolean): Record<string, Schema> {
  // Account documents resolve relative URLs against their own URL and allow only HTTPS.
  const assets = accountOnly ? { type: 'string', pattern: '^(https://|[^:]*$)' } : assetUrl;
  return {
    branding: strict({
      appName: { type: 'string' },
      logoUrl: assets,
      faviconUrl: assets,
      themeUrl: assets,
    }),
    links: strict({
      help: httpUrl,
      privacy: httpUrl,
      terms: {
        type: 'array',
        items: strict({ text: { type: 'string' }, url: httpUrl }, ['text', 'url']),
      },
      supportRoom: { type: 'string' },
      bugReport: httpUrl,
    }),
    hideCommunityLinks: { type: 'boolean', default: false },
    auth: strict({
      ssoRedirect: { enum: ['immediate', 'loginPage', null] },
      disableRegistration: { type: 'boolean', default: false },
      logoutRedirectUrl: httpUrl,
      deviceDisplayName: { type: 'string' },
    }),
    hideUsernamePasswordFields: { type: 'boolean', default: false },
    settingsDefaults: settings,
    settingsLocked: settings,
  };
}

function settingsObject({ specs, placement }: Settings, keys?: readonly string[]): Schema {
  return strict(
    Object.fromEntries(
      specs
        .filter((spec) => !keys || keys.includes(spec.key))
        .map((spec) => [spec.key, settingSchema(spec, placement.get(spec.key)?.label)])
    )
  );
}

function configSchema(settings: Settings): Schema {
  return {
    $schema: 'https://json-schema.org/draft/2020-12/schema',
    title: 'Sable config.json',
    ...strict({
      $schema: { type: 'string' },
      homeserverList: { type: 'array', items: { type: 'string' } },
      defaultHomeserver: nullable({ type: 'integer', minimum: 0 }),
      allowCustomHomeservers: { type: 'boolean', default: true },
      featuredCommunities: strict({ servers: { type: 'array', items: { type: 'string' } } }),
      pushNotificationDetails: nullable(
        strict(
          {
            pushNotifyUrl: { type: 'string' },
            vapidPublicKey: { type: 'string' },
            webPushAppID: { type: 'string' },
            nativePushAppID: { type: ['string', 'null'] },
            iosPushAppID: { type: ['string', 'null'] },
            unifiedPushGatewayUrl: { type: ['string', 'null'] },
            unifiedPushEmbeddedServerUrl: { type: ['string', 'null'] },
          },
          ['pushNotifyUrl', 'vapidPublicKey', 'webPushAppID']
        )
      ),
      embeds: strict({ serviceUrl: httpUrl }),
      supporterAwards: nullable(
        strict(
          {
            serviceUrl: httpUrl,
            keys: {
              type: 'object',
              minProperties: 1,
              additionalProperties: { type: 'string', pattern: '^[A-Za-z0-9+/_-]{43}$' },
            },
          },
          ['serviceUrl', 'keys']
        )
      ),
      gifs: strict({
        provider: { enum: ['klipy', 'tenor', 'giphy'], default: 'tenor' },
        proxyUrl: { type: 'string' },
        klipyApiKey: { type: 'string' },
        tenorApiKey: { type: 'string' },
        giphyApiKey: { type: 'string' },
      }),
      calls: strict({ livekitServiceUrl: { type: 'string' } }),
      searchSharing: strict({
        stunServers: {
          type: 'array',
          items: { type: 'string', pattern: '^stuns?:' },
          default: ['stun:stun.sable.moe:3478'],
        },
      }),
      disableAccountSwitcher: { type: 'boolean', default: false },
      ...policySections(settingsObject(settings), false),
    }),
  };
}

function wellKnownSchema(settings: Settings): Schema {
  return {
    $schema: 'https://json-schema.org/draft/2020-12/schema',
    title: 'Sable /.well-known/sable',
    ...strict({
      $schema: { type: 'string' },
      ...policySections(settingsObject(settings, ACCOUNT_PREFERENCES), true),
    }),
  };
}

const json = (value: unknown) => `${JSON.stringify(value, null, 2)}\n`;

type Parser = {
  type?: string;
  entries?: Schema;
  wrapped?: Parser;
  pipe?: readonly Parser[];
  item?: Parser;
};

function parserFields(parser: Parser): Record<string, Parser> | undefined {
  if (parser.pipe) return parserFields(parser.pipe[0]);
  if (parser.wrapped) return parserFields(parser.wrapped);
  if (parser.type === 'array' && parser.item) return parserFields(parser.item);
  return parser.entries as Record<string, Parser> | undefined;
}

function schemaFields(schema: Schema): Record<string, Schema> | undefined {
  return (schema.properties ?? (schema.items as Schema | undefined)?.properties) as
    | Record<string, Schema>
    | undefined;
}

function fieldDrift(parser: Parser, schema: Schema, path = ''): string[] {
  const read = parserFields(parser);
  const described = schemaFields(schema);
  if (!read || !described) return [];
  return [...new Set([...Object.keys(read), ...Object.keys(described)])]
    .filter((key) => key !== '$schema')
    .flatMap((key) =>
      key in read && key in described
        ? fieldDrift(read[key], described[key], `${path}${key}.`)
        : [`${path}${key}`]
    );
}

describe('configuration reference', () => {
  it('matches the generated settings reference', async () => {
    await expect(settingsMarkdown(await loadSettings())).toMatchFileSnapshot(
      '../../../docs/settings.md'
    );
  });

  it('matches the generated config.json schema', async () => {
    const schema = configSchema(await loadSettings());
    expect(fieldDrift(RuntimeSchema as Parser, schema)).toEqual([]);
    await expect(json(schema)).toMatchFileSnapshot('../../../static/config.schema.json');
  });

  it('matches the generated /.well-known/sable schema', async () => {
    const schema = wellKnownSchema(await loadSettings());
    const fields = Object.keys(RuntimeSchema.pipe[0].entries);
    const accepted = [true, {}].flatMap((value) =>
      Object.keys(
        parseAccountConfig(
          Object.fromEntries(fields.map((key) => [key, value])),
          'https://example.org/.well-known/sable'
        ) ?? {}
      )
    );
    const described = Object.keys(schema.properties as Schema).filter((key) => key !== '$schema');
    expect(accepted.sort()).toEqual(described.sort());
    await expect(json(schema)).toMatchFileSnapshot('../../../static/well-known-sable.schema.json');
  });
});
